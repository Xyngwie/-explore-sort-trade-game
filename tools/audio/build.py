"""Build WRECKLINE's BGM and sound effects into packages/shared/src/audio (MP3 + manifest.json).

Usage (repo root):  python3 tools/audio/build.py
Needs: python3, numpy, scipy, ffmpeg (libmp3lame). Deterministic: the same code gives the same audio.

Looping BGM is written with a margin of its own end before it and its own start after it.
The manifest's `loop` is the exact one-period region. Whatever lead-in a browser's MP3 decoder adds or
drops, a window of exactly one period inside continuous periodic audio still loops without a seam.
"""
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from synth import SR, write_mp3  # noqa: E402
import songs  # noqa: E402
import songs2  # noqa: E402
import sfx  # noqa: E402

OUT = os.path.join(HERE, "..", "..", "packages", "shared", "src", "audio")
MARGIN = 0.5  # seconds of wrap-around on each side of a loop

BGM = [
    # (id, title, function, loops)
    ("title", "WRECKLINE - Above the Shell", songs2.title, False),
    ("hangar", "Hangar - Rust and Warmth", songs.hangar, True),
    ("recon", "Recon Grid", songs2.recon, True),
    ("sorting", "Sorting the Salvage", songs2.sorting, True),
    ("restoring", "Restoring the Circuit", songs2.restoring, True),
    ("briefing", "Briefing - Mass Driver", songs2.briefing, True),
    ("scavenging", "Scavenging the Shell", songs2.scavenging, True),
    ("contact", "Contact", songs.contact, True),
    ("extraction", "Extraction Window", songs2.extraction, True),
    ("home", "Home with Cargo", songs2.home, True),
    ("lost", "Lost to the Cold", songs2.lost, True),
]

SFX_ID = {name: name for name, _label, _fn in sfx.SFX}


def build_bgm(manifest):
    os.makedirs(os.path.join(OUT, "bgm"), exist_ok=True)
    for key, title, fn, loops in BGM:
        x = fn()
        entry = {"file": f"bgm/{key}.mp3", "title": title, "loop": None}
        if loops:
            m = int(MARGIN * SR)
            body = np.concatenate([x[-m:], x, x[:m]])
            entry["loop"] = [round(MARGIN, 6), round(MARGIN + len(x) / SR, 6)]
        else:
            body = x
        write_mp3(body, os.path.join(OUT, entry["file"]), title, kbps=128)
        manifest["bgm"][key] = entry
        print("bgm", key, flush=True)


def build_sfx(manifest):
    os.makedirs(os.path.join(OUT, "sfx"), exist_ok=True)
    tiers = sfx.TIER
    for name, label, fn in sfx.SFX:
        x = fn()
        path = os.path.join(OUT, "sfx", f"{name}.mp3")
        write_mp3(np.stack([x, x], axis=1), path, f"SFX {name}", kbps=64, channels=1)
        peak_db = 20 * np.log10(np.max(np.abs(x)) + 1e-12)
        tier = min(tiers, key=lambda t: abs(tiers[t] - peak_db))
        manifest["sfx"][name] = {"file": f"sfx/{name}.mp3", "label": label, "tier": tier}
    print("sfx", len(sfx.SFX), flush=True)


def write_urls(manifest):
    """packages/shared/src/audio-urls.ts: one literal new URL per file so Vite bundles each one."""
    lines = [
        "/** Generated by tools/audio/build.py. Do not edit. One literal URL per file so Vite bundles it. */",
        "export const BGM_URLS = {",
    ]
    for key, entry in manifest["bgm"].items():
        lines.append(f'  "{key}": new URL("./audio/{entry["file"]}", import.meta.url).href,')
    lines += ["} as const;", "", "export const SFX_URLS = {"]
    for key, entry in manifest["sfx"].items():
        lines.append(f'  "{key}": new URL("./audio/{entry["file"]}", import.meta.url).href,')
    lines += ["} as const;", ""]
    with open(os.path.join(OUT, "..", "audio-urls.ts"), "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    only = set(sys.argv[1:])
    path = os.path.join(OUT, "manifest.json")
    manifest = {"bgm": {}, "sfx": {}}
    if os.path.exists(path) and only:
        with open(path) as f:
            manifest = json.load(f)
    if not only or "bgm" in only:
        manifest["bgm"] = {}
        build_bgm(manifest)
    if not only or "sfx" in only:
        manifest["sfx"] = {}
        build_sfx(manifest)
    if only != {"urls"}:
        with open(path, "w") as f:
            json.dump(manifest, f, ensure_ascii=False, indent=2)
            f.write("\n")
    write_urls(manifest)
    print("manifest", path)
