import assert from "node:assert/strict";
import { createWorld, bootstrapFromSearch, startSortie } from "./game/world";
import { collectSupplies, initializeEnemy } from "./game/enemyBehavior";
import { updateEnemies } from "./game/sim";
import { combatFeedback, tickCombatFeedback, feedbackLabel } from "./game/combatFeedback";
import { attachCircuitPlay } from "./game/circuitPlay";
import { getCoverObjects } from "./game/coverObjects";
const w = createWorld(bootstrapFromSearch("")); startSortie(w);
w.wingmen = []; w.enemies = w.enemies.slice(0,1);
const e = w.enemies[0]!;
e.enemyIdentity!.circuits = [];
initializeEnemy(e, () => .5);
e.pos = { ...w.leader.pos, x: w.leader.pos.x + 60 };
e.enemyState!.ammo = 1; e.enemyState!.activity = e.enemyState!.capacity * .1;
e.cooldown = 0; e.heading = Math.PI; // facing PR1: already aimed at the leader
getCoverObjects(w).splice(0);
updateEnemies(w, .01);
assert.equal(e.enemyState!.ammo, 0);
assert.equal(combatFeedback(w).filter(x => x.kind === "empty").length, 1);
updateEnemies(w, 2);
assert.equal(combatFeedback(w).length, 1, "empty attempts never repeat the indicator");
tickCombatFeedback(w, 2); assert.equal(combatFeedback(w).length, 0);
e.enemyState!.ammo = 1; e.cooldown = 0;
updateEnemies(w, .01);
assert.equal(combatFeedback(w).length, 1, "refilled enemy can run out again");
w.enemies = []; tickCombatFeedback(w, 2);
w.leader.instanceId = "test";
w.currentAmmo.test = 27;
w.mechBattery.test = { activity: 290, capacity: 300 };
w.enemySupplies = [{ id:"supply", pos:{...w.leader.pos}, ammo:10, power:100 }];
collectSupplies(w);
const events = combatFeedback(w);
assert.equal(events.find(x => x.kind === "ammo")?.amount, 1, "only space actually filled");
assert.ok(Math.abs(events.find(x => x.kind === "power")!.amount - 10) < .00001);
assert.equal(w.enemySupplies[0]!.ammo, 9);
assert.ok(Math.abs(w.enemySupplies[0]!.power - 90) < .00001);
collectSupplies(w);
assert.equal(combatFeedback(w).length, 2, "full units emit no zero pickups");
assert.equal(feedbackLabel(events.find(x => x.kind === "ammo")!), "弾薬 +1");
assert.equal(combatFeedback(JSON.parse(JSON.stringify(w))).length, 0, "checkpoint does not replay presentation");
console.log("combat feedback: depletion, refill, actual pickup caps, full units, expiry, checkpoint PASS");

const armed = createWorld(bootstrapFromSearch("")); startSortie(armed);
armed.wingmen = []; armed.enemies = armed.enemies.slice(0,1);
const gunner = armed.enemies[0]!;
gunner.enemyIdentity!.circuits = gunner.enemyIdentity!.circuits.slice(0,1);
gunner.enemyIdentity!.circuits[0]!.effectKey = "shotgun";
initializeEnemy(gunner, () => .5);
attachCircuitPlay(armed, null, false);
gunner.pos = { ...armed.leader.pos, x: armed.leader.pos.x + 60 };
gunner.enemyState!.ammo = 1; gunner.enemyState!.activity = 0; gunner.cooldown = 0; gunner.heading = Math.PI;
getCoverObjects(armed).splice(0);
updateEnemies(armed, .01);
assert.equal(gunner.enemyState!.ammo, 0);
assert.equal(combatFeedback(armed).filter(x => x.kind === "empty").length, 1, "circuit weapon also emits depletion");
console.log("combat feedback: circuit weapon depletion PASS");
