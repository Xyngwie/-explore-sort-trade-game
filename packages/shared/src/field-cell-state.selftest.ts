import assert from 'node:assert/strict';
import { INITIAL_HUB, normalizeHubSnapshot, createHubSave, serializeHubSave, deserializeHubSave, setFrontProgressInHub, clearFrontProgressInHub } from './hub-save';
import { emptyFieldObjectIdentities, registerWreckIdentity, shieldIdentityFromWreck } from './field-object-identities';
import { applyFieldCellReport, normalizeFieldCellReport, type FieldCellReport } from './field-cell-state';
import { buildExploreToHubWearUrl, parseExploreToHubWearSearch, type ExploreToHubWearPayload } from './handoff';
import { applyExploreReturnToHub } from './sortie-return';
const location={frontSeed:812,cell:{sx:1,sy:2}};
let identities=registerWreckIdentity(emptyFieldObjectIdentities(),'source');
identities=shieldIdentityFromWreck(identities,'source','shield',{hp:23.5,maxHp:50});
identities=registerWreckIdentity(identities,'enemy-w');
const report:FieldCellReport={location,ground:{shield:{x:123.4,y:555.6}},wrecks:[{
 targetId:'enemy-field-test',wreckKey:'enemy-w',pos:{x:200,y:300},sourceInstanceId:null,seconds:3.25,shieldMaxHp:62.75,
 circuits:[{circuitId:'exact-c',side:3,effect:7}],enemy:{name:'敵',maxHp:100,radius:14,heading:2,identity:{modelId:'mech_gen1',durability:100,circuits:[{circuitId:'exact-c',side:3,effect:7,effectKey:'smg',trueBoard:false}]}},
}],identities};
const hub=normalizeHubSnapshot({...INITIAL_HUB,frontProgress:{seed:812,aoiHalf:12,opened:[],flagged:[],focus:null}});
const wear:ExploreToHubWearPayload={returnKind:'extract',sortieId:'field-once',mechWear:[],frontSeed:812,cell:location.cell,fieldCell:report};
const original=structuredClone(hub);
const payload=parseExploreToHubWearSearch(new URL(buildExploreToHubWearUrl(wear,'https://example.test/')).search)!;
assert.deepEqual(JSON.parse(JSON.stringify(payload.fieldCell)),JSON.parse(JSON.stringify(report)),'URL keeps exact HP/position/ID/progress/circuits');
const result=applyExploreReturnToHub(hub,payload);assert(result.applied);
const saved=deserializeHubSave(serializeHubSave(createHubSave(result.hub)))!;
assert.deepEqual(saved.hub.fieldCells,result.hub.fieldCells);
assert.equal(saved.hub.fieldObjectIdentities!.shields.shield!.hp,23.5);
assert.equal(saved.hub.fieldCells![0]!.wrecks[0]!.seconds,3.25);
assert.equal(saved.hub.fieldCells![0]!.wrecks[0]!.shieldMaxHp,62.75,'new stripping max HP survives URL and normalized save');
assert.equal(applyExploreReturnToHub(saved.hub,payload).applied,false,'once even after serialized reload');
assert.deepEqual(hub,original,'input untouched');
const other={...report,location:{frontSeed:812,cell:{sx:4,sy:4}},ground:{},wrecks:[]};
const both=applyFieldCellReport(result.hub,other);assert.equal(both.fieldCells!.length,2);
const empty=applyFieldCellReport(both,{...report,ground:{},wrecks:[]});
assert.equal(empty.fieldCells!.length,2);assert.deepEqual(empty.fieldCells![1]!.ground,{});
assert.equal(empty.fieldObjectIdentities!.shields.shield,undefined,'picked or broken shield must not resurrect');
assert.deepEqual(empty.fieldCells![0]!.location,other.location,'other cell unchanged');
assert.equal(empty.fieldObjectIdentities!.nextWreckId,identities.nextWreckId);
const counter=result.hub.fieldObjectIdentities!.nextWreckId;
const regen=setFrontProgressInHub(result.hub,{...hub.frontProgress!,seed:999});
assert.deepEqual(regen.fieldCells,[]);assert.equal(regen.fieldObjectIdentities!.shields.shield,undefined);
assert.equal(regen.fieldObjectIdentities!.nextWreckId,counter,'board regeneration never recycles IDs');
assert.equal(applyFieldCellReport(regen,report),regen,'late old-board report ignored');
assert.deepEqual(clearFrontProgressInHub(result.hub).fieldCells,[]);
assert.equal(normalizeHubSnapshot(INITIAL_HUB).fieldCells,undefined,'legacy absence remains absent');
assert.equal(normalizeFieldCellReport({...report,ground:{shield:{x:NaN,y:1}}}),undefined);
assert.equal(normalizeFieldCellReport({...report,wrecks:[{...report.wrecks[0],seconds:8}]}),undefined);
assert.throws(()=>normalizeHubSnapshot({...result.hub,fieldCells:[{...report,ground:{missing:{x:1,y:1}}}]}),'malformed save refused rather than silently losing objects');
assert.equal(parseExploreToHubWearSearch('?returnKind=extract&fieldCell=broken')!.fieldCell,undefined);
const mismatched=applyExploreReturnToHub(hub,{...wear,sortieId:'mismatch',cell:{sx:0,sy:0}});
assert.equal(mismatched.hub.fieldCells,undefined,'mixed location metadata is not accepted');
const acquired=applyExploreReturnToHub(hub,{...wear,sortieId:'mixed-acquired',enemyWrecks:[{instanceId:'recovered-enemy-field-test',circuits:[]}]});
assert.equal(acquired.hub.fieldCells![0]!.wrecks.length,0,'recovered enemy cannot also persist on the field');
console.log('Field cells PASS: save/URL/once, precise HP and identity, other cells, empty replacement, board reset/high-water, stale/mixed/recovered data, old/invalid saves');
